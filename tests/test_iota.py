"""Iota rules (harness/kernel3/iota.py) and its differential test.

ROADMAP 2c, the third and last of the third check's assumed properties. The
recursor pass counts the rules and checks which constructor each belongs to;
this pass re-derives each rule's right-hand side from the constructor and the
recursor and compares it, so an OK means the stored rule IS the derived one.

Its vectors had to be generated by Lean rather than hand-written, unlike the
other three: what needs demonstrating is that a tampered rule is invisible in
an otherwise clean export, which needs the base to be clean. Two pairs, each
differing from its control in one line:

  * `control_iota` / `forge_iota` — the two iota rules of `Two.rec` swapped,
    and nothing in the export exercising them. Both give `8 checked, 0 errors`
    from the third check. Only this pass separates them. That is the hole.
  * `control_iota_exercised` / `forge_iota_exercised` — the same swap plus
    `pick_fst : pick a b Two.fst = a := rfl`, which the correct rule justifies
    and the swapped one does not. The term layer rejects the forged one. That
    is the consequence.

Neither forgery proves `False`, and `test_the_iota_forgery_does_not_prove_false`
records why: a wrong iota rule gives a consistent system that computes
something other than the declaration says.
"""
import json
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "harness"))
from kernel3.parse import parse_export                     # noqa: E402
from kernel3.iota import (check_env, check_rule, expected_rhs,  # noqa: E402
                          alpha_eq, relabel, strip_gadgets,
                          GADGETS, NESTED, NOT_IN_EXPORT)
from kernel3.check import check_env as third_check          # noqa: E402
from kernel3.check import baseline_fingerprints             # noqa: E402

FORGE = ROOT / "tests" / "forgeries"
DIFF = ROOT / "evidence" / "iota_differential.json"

PAIRS = [("control_iota", "forge_iota"),
         ("control_iota_exercised", "forge_iota_exercised")]


def load(name: str):
    old = sys.getrecursionlimit()
    sys.setrecursionlimit(60000)
    try:
        return parse_export(str(FORGE / f"{name}.export"))
    finally:
        sys.setrecursionlimit(old)


def nm(env, name: str):
    for n in env.order:
        if str(n) == name:
            return n
    raise AssertionError(f"{name} not in export")


# ------------------------------------------------- A. the adversarial vectors
@pytest.mark.parametrize("control,forged", PAIRS)
def test_each_pair_differs_in_one_line(control, forged):
    """The forgery is one token of one line. If these files ever drift apart
    in anything else, whatever the pass reports about them stops being about
    the iota rules."""
    a = (FORGE / f"{control}.export").read_text(encoding="utf-8").splitlines()
    b = (FORGE / f"{forged}.export").read_text(encoding="utf-8").splitlines()
    assert len(a) == len(b)
    diff = [i for i, (x, y) in enumerate(zip(a, b)) if x != y]
    assert len(diff) == 1, diff
    assert a[diff[0]].startswith("#REC ")


@pytest.mark.parametrize("control,forged", PAIRS)
def test_the_swapped_rule_is_rejected_on_the_rule(control, forged):
    """The ROADMAP 2c 'done when'. The control must be clean, or the
    rejection says nothing."""
    assert check_env(load(control))["violations"] == []
    v = check_env(load(forged))["violations"]
    assert len(v) == 1, v
    name, why = v[0]
    assert name == "Two.rec"
    assert "Two.fst" in why
    assert "not what" in why


def test_the_hole_is_invisible_to_the_third_check():
    """The pair that matters: the third check reports the forged export as
    clean as the control. The rules are not part of what it derives, so a
    swapped rule costs nothing there -- which is the gap this pass closes."""
    old = sys.getrecursionlimit()
    sys.setrecursionlimit(60000)
    try:
        clean = third_check(load("control_iota"))
        forged = third_check(load("forge_iota"))
    finally:
        sys.setrecursionlimit(old)
    assert clean["errors"] == []
    assert forged["errors"] == [], (
        "the forged export is no longer clean to the third check; the vector "
        "has stopped demonstrating the hole")
    assert clean["checked"] == forged["checked"]


def test_the_consequence_is_demonstrated_not_asserted():
    """The exercised pair: once a term depends on the rule, what the kernel
    proves changes. `pick a b Two.fst = a` is true of `pick` as declared and
    provable by `rfl` only because the rule for `Two.fst` returns the first
    minor premise; with the rules swapped that proof fails."""
    old = sys.getrecursionlimit()
    sys.setrecursionlimit(60000)
    try:
        clean = third_check(load("control_iota_exercised"))
        forged = third_check(load("forge_iota_exercised"))
    finally:
        sys.setrecursionlimit(old)
    assert clean["errors"] == []
    assert len(forged["errors"]) == 1
    where, message = forged["errors"][0]
    assert "pick_fst" in str(where)
    assert "declared type" in str(message)


def test_the_iota_forgery_does_not_prove_false():
    """Recorded as a property of the vector, not an omission.

    A swapped iota rule cannot be turned into a proof of `False`: a minor
    premise's required type comes from the recursor's TYPE, and the forged
    reduction only changes the result side, so the hard minor still blocks the
    construction. What a wrong rule gives is a consistent system that computes
    something other than the declaration says -- the ASSUMPTIONS A1 failure
    mode, not an inconsistency. If someone later builds a False-proving iota
    vector, this test is the thing to delete, deliberately."""
    for _control, forged in PAIRS:
        env = load(forged)
        names = {str(n) for n in env.order}
        assert "False" not in names
        assert not any(s.endswith("MyFalse") for s in names)


@pytest.mark.parametrize("other", ["forge_positivity", "forge_large_elim"])
def test_the_other_forgeries_pass_this_pass(other):
    """Each forgery must fail exactly the pass that owns the property it
    forges. `forge_positivity`'s rules are the ones Lean derives, and so are
    `forge_large_elim`'s -- what the latter forges is the recursor's type."""
    r = check_env(load(other))
    assert r["violations"] == [], r["violations"]


def test_iota_pass_does_not_relax_the_provenance_gate():
    old = sys.getrecursionlimit()
    sys.setrecursionlimit(60000)
    try:
        env = load("forge_iota")
        base = baseline_fingerprints(load("control_iota"))
        out = third_check(env, baseline=base)
    finally:
        sys.setrecursionlimit(old)
    assert out["introduced_assumptions"], (
        "the forged recursor is no longer reported as introduced")


# ------------------------------------------- B. what the derivation may ignore
def test_gadgets_are_stripped_on_the_derived_side_only():
    """`optParam`/`autoParam` are elaboration wrappers Lean strips when it
    generates a rule's binders, so the derivation strips them too -- 15 of
    Lean's own Init declarations read as forged before it did.

    Stripping must stay one-sided. A symmetric strip would stop the
    comparison seeing a wrapper a forgery introduced, which is a widening
    dressed up as a normalization."""
    src = (ROOT / "harness" / "kernel3" / "iota.py").read_text(encoding="utf-8")
    assert "strip_gadgets(relabel(" in src, (
        "the derived field binder is no longer gadget-stripped")
    assert not re.search(r"strip_gadgets\((got|rhs|stored)", src), (
        "gadgets are being stripped from the STORED rule as well")
    assert set(GADGETS) == {"optParam", "autoParam"}


def test_gadget_stripping_only_unwraps_two_argument_applications():
    env = load("control_iota")
    two = env.get(nm(env, "Two"))
    # a type with no gadget is returned untouched
    assert strip_gadgets(two.type) is two.type


def test_alpha_eq_ignores_binder_names_and_nothing_else():
    """`Expr` interns on the binder name and compares by identity, so a
    name-sensitive comparison reports every rule forged -- Lean calls the same
    field `h` in one rule and `a._@._internal._hyg.0` in the next. But alpha_eq
    must still see a changed index, constant or universe."""
    from kernel3.terms import lam, bvar, const, sort, ZERO, Name
    a = lam(Name.mk(("x",)), sort(ZERO), bvar(0))
    b = lam(Name.mk(("y",)), sort(ZERO), bvar(0))
    assert a is not b
    assert alpha_eq(a, b)
    assert not alpha_eq(a, lam(Name.mk(("x",)), sort(ZERO), bvar(1)))
    assert not alpha_eq(const(Name.mk(("A",)), []), const(Name.mk(("B",)), []))


def test_relabel_descends_into_let():
    """Six of Lean's own structures have a field whose type opens with a
    `let`. Skipping that case left every index inside one unrewritten, and the
    pass reported them forged."""
    src = (ROOT / "harness" / "kernel3" / "iota.py").read_text(encoding="utf-8")
    assert "if k == LET:" in src
    from kernel3.terms import Expr, LET, bvar, sort, ZERO, Name
    e = Expr._mk(LET, a=sort(ZERO), b=bvar(0), c=bvar(1), name=Name.mk(("v",)))
    out = relabel(e, lambda k: k + 10)
    assert out.b.idx == 10          # the value: free, shifted
    assert out.c.idx == 11          # the body: one binder deeper, still free


# ----------------------------------------------- C. the differential record
def test_differential_record_is_consistent():
    d = json.loads(DIFF.read_text(encoding="utf-8"))
    assert d["schema"] == "ampas-iota-differential/1"
    assert d["pass"] == "iota"
    t = d["totals"]
    assert t["checked"] == sum(s["checked"] for s in d["sets"])
    assert t["ok"] == sum(s["ok"] for s in d["sets"])
    for s in d["sets"]:
        assert s["checked"] == (
            s["ok"] + len(s["violations"]) + len(s["unclassified"])), s["environment"]
        assert sum(s["unclassified_by_cause"].values()) == len(s["unclassified"])
        assert s["unclassified_by_cause"].get("other", 0) == 0


def test_differential_record_reports_no_violation():
    """Lean generated every one of these rules itself, so a violation would be
    a bug in the pass. Three were, and each was found only here: the first
    version used the rule body's binder depth for a field's own binder type,
    skipped `let`, and called this recursor for a field of a sibling's type in
    a mutual family. The first failed 491 of 627 recursors, the last failed 25
    in Mathlib and none in Lean's Init -- which has no mutual inductive in the
    set, so the core run alone would have passed it."""
    d = json.loads(DIFF.read_text(encoding="utf-8"))
    assert d["totals"]["violations"] == 0
    for s in d["sets"]:
        assert s["violations"] == [], s["environment"]


def test_differential_record_covers_both_environments():
    d = json.loads(DIFF.read_text(encoding="utf-8"))
    envs = {s["environment"] for s in d["sets"]}
    assert "AmpasRef.Guards" in envs
    assert any("Mathlib" in e for e in envs), envs
    assert d["totals"]["checked"] > 1000
    assert d["totals"]["ok"] > 3000, (
        "the point of this pass is that the rules ARE re-derivable at scale")


def test_differential_record_does_not_claim_the_export_came_from_lean():
    """All three passes check a declaration against the rules Lean would have
    followed. None shows Lean produced it, and the record must not imply
    otherwise: that is the provenance gate's job and the boundary A3 is
    written against."""
    d = json.loads(DIFF.read_text(encoding="utf-8"))
    means = " ".join(d["means"])
    assert "provenance" in means
    assert "came from Lean" in means or "did not come from Lean" in means


def test_unclassified_is_almost_entirely_the_nested_case():
    """If this starts drifting, the pass is declining things it used to
    derive, and the record is where that shows."""
    d = json.loads(DIFF.read_text(encoding="utf-8"))
    total = d["totals"]["unclassified"]
    nested = sum(s["unclassified_by_cause"].get("nested auxiliary recursor", 0)
                 for s in d["sets"])
    assert total > 0
    assert nested == total, (
        f"{total - nested} declined for a reason other than nesting")
    assert NESTED and NOT_IN_EXPORT, "the causes must be tagged constants"


# ------------------------------------------------------------ the derivation
def test_expected_rhs_matches_the_stored_rule_for_a_real_recursor():
    env = load("control_iota")
    rec = env.get(nm(env, "Two.rec"))
    family = list(rec.all_names)
    inds = [env.get(n) for n in family]
    all_ctors = [c for i in inds for c in i.ctors]
    for cname, nfields, rhs in rec.rules:
        ctor = env.get(cname)
        verdict, why = check_rule(rec, ctor, nfields, rhs,
                                  all_ctors.index(cname), env, family)
        assert verdict == "OK", f"{cname}: {why}"


def test_a_rule_with_the_wrong_field_count_is_a_violation():
    env = load("control_iota")
    rec = env.get(nm(env, "Two.rec"))
    family = list(rec.all_names)
    cname, nfields, rhs = rec.rules[0]
    ctor = env.get(cname)
    verdict, why = check_rule(rec, ctor, nfields + 1, rhs, 0, env, family)
    assert verdict == "VIOLATION"
    assert "fields" in why


def test_the_derivation_declines_rather_than_crashing_or_guessing():
    """When the de Bruijn arithmetic cannot be carried out, the pass must come
    back UNCLASSIFIED -- not raise, and not build a partial term the
    comparison would then treat as authoritative.

    Driven behaviourally: a recursor claiming more parameters than the
    constructor has binders makes every index escape the telescope."""
    env = load("control_iota")
    rec = env.get(nm(env, "Two.rec"))
    family = list(rec.all_names)
    cname, nfields, rhs = rec.rules[0]
    ctor = env.get(cname)
    import dataclasses
    broken = dataclasses.replace(rec, num_params=rec.num_params + 40)
    want, why = expected_rhs(broken, ctor, 0, env, family)
    assert (want is None) or (why is None)
    verdict, reason = check_rule(broken, ctor, nfields, rhs, 0, env, family)
    assert verdict in ("UNCLASSIFIED", "VIOLATION"), reason
    assert reason


