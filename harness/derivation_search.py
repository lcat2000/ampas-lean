#!/usr/bin/env python3
"""Bounded derivation search against the frozen independence claims.

The numeric counterexample search (harness/counterexample.py) cannot touch
these four. `PL.Derives`, `PL.DerivesPos` and `EL.Derives` are inductively
defined predicates with no decision procedure, so there is no box of numbers
to enumerate and those claims come back NOT_SEARCHABLE. One of them, PL-BOGUS,
is a declared-FALSE control whose falsity therefore rested on a reviewer's
reading alone.

A claim of the form `Independent T phi` says two derivations do not exist. So
a counterexample is a DERIVATION, and the way to find one is to enumerate
derivations rather than values:

  * Propositional: forward-chain modus ponens over axiom instances. The axiom
    schemas range over all formulas, so the instances are infinite; the search
    instantiates them over a FINITE formula universe grown from the goal, the
    theory and whatever has been derived so far. That is the bound, and it is
    reported, because "no derivation" always means "none within this universe
    and this many rounds".
  * Equational: congruence closure over a finite term universe, with axiom
    instances under substitutions drawn from that universe.

**This program is not trusted.** It only finds candidates. Every derivation it
finds is emitted as a Lean term proving the NEGATION of the frozen statement,
and the verdict recorded is the Lean kernel's, not this program's -- checked
by harness/CheckRefutation.lean, which also verifies that the refutation's
type really is `Not` applied to the frozen statement rather than to something
adjacent. A bug here can therefore lose a refutation; it cannot manufacture
one.

What a negative result does and does not mean is in ASSUMPTIONS A1c.

Usage:
  python3 harness/derivation_search.py --out build/derivation_search.json
"""
from __future__ import annotations

import argparse
import json
import time
from dataclasses import dataclass
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


# --------------------------------------------------------------------------
# Propositional formulas, mirroring Ampas.PL.Fm exactly
# --------------------------------------------------------------------------
# ("var", i) | ("imp", a, b) | ("neg", a)
Fm = tuple


def var(i: int) -> Fm:
    return ("var", i)


def imp(a: Fm, b: Fm) -> Fm:
    return ("imp", a, b)


def neg(a: Fm) -> Fm:
    return ("neg", a)


def fm_size(f: Fm) -> int:
    if f[0] == "var":
        return 1
    if f[0] == "neg":
        return 1 + fm_size(f[1])
    return 1 + fm_size(f[1]) + fm_size(f[2])


def fm_lean(f: Fm) -> str:
    """The same formula as a Lean term over Ampas.PL.Fm."""
    if f[0] == "var":
        return f"(.var {f[1]})"
    if f[0] == "neg":
        return f"(.neg {fm_lean(f[1])})"
    return f"(.imp {fm_lean(f[1])} {fm_lean(f[2])})"


def subformulas(f: Fm, acc: set | None = None) -> set:
    acc = set() if acc is None else acc
    acc.add(f)
    if f[0] == "neg":
        subformulas(f[1], acc)
    elif f[0] == "imp":
        subformulas(f[1], acc)
        subformulas(f[2], acc)
    return acc


@dataclass
class Step:
    """One line of a derivation: the rule, and where its premises came from."""
    rule: str                  # hyp | a1 | a2 | a3 | mp
    formula: Fm
    premises: tuple = ()       # indices into the derivation list


def pl_search(theory: list[Fm], targets: list[Fm], *, positive: bool,
              universe_size: int, rounds: int) -> tuple[dict, list[Step]] | tuple[dict, None]:
    """Forward-chain from axiom instances and the theory, looking for a target.

    The formula universe starts as the subformulas of the goals, the theory and
    the axioms' own shape, and grows with each round from what has been
    derived. Axiom instances are generated by substituting universe members
    into the schemas; modus ponens combines derived formulas. Both are capped,
    and the caps are part of the result.
    """
    universe: set = set()
    for f in theory + targets:
        universe |= subformulas(f)
    # proofs: formula -> Step, and the order they were derived in
    derivation: list[Step] = []
    index: dict = {}

    def add(step: Step) -> int | None:
        if step.formula in index:
            return None
        index[step.formula] = len(derivation)
        derivation.append(step)
        return len(derivation) - 1

    for f in theory:
        add(Step("hyp", f))

    stats = {"rounds_run": 0, "universe": 0, "axiom_instances": 0, "derived": 0}
    for r in range(rounds):
        stats["rounds_run"] = r + 1
        # 1. axiom instances over the current universe
        pool = sorted(universe, key=lambda f: (fm_size(f), str(f)))[:universe_size]
        stats["universe"] = len(pool)
        instances = 0
        for a, b in product(pool, repeat=2):
            add(Step("a1", imp(a, imp(b, a))))
            instances += 1
            if not positive:
                add(Step("a3", imp(imp(neg(a), neg(b)), imp(b, a))))
                instances += 1
        for a, b, c in product(pool, repeat=3):
            add(Step("a2", imp(imp(a, imp(b, c)), imp(imp(a, b), imp(a, c)))))
            instances += 1
        stats["axiom_instances"] = instances

        # 2. modus ponens to fixpoint over what is derived
        while True:
            grew = False
            implications = [(i, s) for i, s in enumerate(derivation)
                            if s.formula[0] == "imp"]
            for i, s in implications:
                ante, cons = s.formula[1], s.formula[2]
                j = index.get(ante)
                if j is None or cons in index:
                    continue
                add(Step("mp", cons, (i, j)))
                grew = True
            if not grew:
                break
        stats["derived"] = len(derivation)

        for t in targets:
            if t in index:
                return stats, _trace(derivation, index[t])

        # 3. grow the universe from what was derived, for the next round
        before = len(universe)
        for s in derivation:
            universe |= subformulas(s.formula)
        if len(universe) == before:
            break                      # nothing new to instantiate with
    return stats, None


def _trace(derivation: list[Step], i: int) -> list[Step]:
    """The sub-derivation reaching step i, in dependency order."""
    need, order, seen = [i], [], set()

    def visit(k: int):
        if k in seen:
            return
        seen.add(k)
        for p in derivation[k].premises:
            visit(p)
        order.append(k)

    visit(i)
    remap = {k: n for n, k in enumerate(order)}
    return [Step(derivation[k].rule, derivation[k].formula,
                 tuple(remap[p] for p in derivation[k].premises)) for k in order]


def pl_term(steps: list[Step], ctor: str) -> str:
    """The derivation as a Lean term over `Ampas.PL.Derives` constructors.

    Written out as a `let`-free nested application so the kernel checks the
    whole tree: each step's type is forced by the constructor and its
    premises, so a step that does not follow cannot be written down.
    """
    out = []
    for s in steps:
        if s.rule == "hyp":
            out.append("(.hyp rfl)")
        elif s.rule in ("a1", "a2", "a3"):
            out.append(f"(.{s.rule})")
        else:
            i, j = s.premises
            out.append(f"(.mp {out[i]} {out[j]})")
    return out[-1]


# --------------------------------------------------------------------------
# Equational logic, mirroring Ampas.EL
# --------------------------------------------------------------------------
# ("var", i) | ("one",) | ("mul", a, b)
def tvar(i: int) -> tuple:
    return ("var", i)


ONE = ("one",)


def mul(a, b) -> tuple:
    return ("mul", a, b)


def t_size(t) -> int:
    if t[0] in ("var", "one"):
        return 1
    return 1 + t_size(t[1]) + t_size(t[2])


def subterms(t, acc=None) -> set:
    acc = set() if acc is None else acc
    acc.add(t)
    if t[0] == "mul":
        subterms(t[1], acc)
        subterms(t[2], acc)
    return acc


def t_subst(t, sigma: dict):
    if t[0] == "var":
        return sigma.get(t[1], t)
    if t[0] == "one":
        return t
    return mul(t_subst(t[1], sigma), t_subst(t[2], sigma))


MONOID = [((mul(mul(tvar(0), tvar(1)), tvar(2))), mul(tvar(0), mul(tvar(1), tvar(2)))),
          (mul(ONE, tvar(0)), tvar(0)),
          (mul(tvar(0), ONE), tvar(0))]
COMM = (mul(tvar(0), tvar(1)), mul(tvar(1), tvar(0)))


def el_search(axioms: list[tuple], goal: tuple, *, term_depth: int,
              subst_pool: int) -> tuple[dict, bool]:
    """Congruence closure over a finite term universe.

    Union-find over terms, seeded with every axiom instance whose two sides
    both lie in the universe, then closed under congruence to a fixpoint.
    Returns whether the goal's two sides became equal.
    """
    base: set = set()
    for l, r in axioms:
        base |= subterms(l) | subterms(r)
    base |= subterms(goal[0]) | subterms(goal[1])
    atoms = sorted({t for t in base if t[0] in ("var", "one")}, key=str)
    universe = set(atoms)
    capped = False
    for _ in range(term_depth):
        if len(universe) ** 2 > 300_000:
            # A cap that is checked BEFORE expanding, so it is a cap: the
            # previous version tested afterwards and a single round could
            # overshoot it fiftyfold without the record saying so.
            capped = True
            break
        universe |= {mul(a, b) for a, b in product(sorted(universe, key=str), repeat=2)}
        universe |= base
    pool = sorted(universe, key=lambda t: (t_size(t), str(t)))[:subst_pool]

    parent: dict = {t: t for t in universe}

    def find(t):
        while parent[t] != t:
            parent[t] = parent[parent[t]]
            t = parent[t]
        return t

    def union(a, b) -> bool:
        ra, rb = find(a), find(b)
        if ra == rb:
            return False
        parent[rb] = ra
        return True

    instances = 0
    for l, r in axioms:
        vs = sorted({i for t in (l, r) for i in _vars(t)})
        for combo in product(pool, repeat=len(vs)):
            sigma = dict(zip(vs, combo))
            li, ri = t_subst(l, sigma), t_subst(r, sigma)
            if li in parent and ri in parent:
                union(li, ri)
                instances += 1

    # congruence to fixpoint
    for _ in range(64):
        grew = False
        buckets: dict = {}
        for t in universe:
            if t[0] != "mul":
                continue
            k = (find(t[1]), find(t[2]))
            if k in buckets:
                grew |= union(buckets[k], t)
            else:
                buckets[k] = t
        if not grew:
            break

    return ({"term_universe": len(universe), "substitution_pool": len(pool),
             "axiom_instances": instances, "universe_capped": capped,
             "term_depth": term_depth},
            find(goal[0]) == find(goal[1]) if goal[0] in parent and goal[1] in parent
            else False)


def _vars(t) -> set:
    if t[0] == "var":
        return {t[1]}
    if t[0] == "one":
        return set()
    return _vars(t[1]) | _vars(t[2])


# --------------------------------------------------------------------------
# Witness emission: the derivation as a Lean file the KERNEL checks
# --------------------------------------------------------------------------
def pl_witness_lean(name: str, claim: str, steps: list[Step], derives: str,
                    theory: str, target: str, conjunct: int) -> str:
    """A Lean file proving the NEGATION of the frozen statement.

    Every step carries its full type, so each line is checked on its own
    rather than resting on Lean inferring what the search had in mind. The
    file is generated, never edited by hand, and nothing trusts it: it is
    compiled and kernel-replayed, and `harness/CheckRefutation.lean` checks
    separately that the type it proves is `Not` applied to the frozen
    statement and not to something adjacent to it.
    """
    lines = [
        "/-",
        f"GENERATED by harness/derivation_search.py -- do not edit.",
        "",
        f"A refutation of the frozen statement of {claim}: the derivation below",
        "exists, so the claim that it does not is false. The search that found it",
        "is not trusted; this file is, only to the extent that the Lean kernel",
        "accepts it.",
        "-/",
        "import AmpasRef.Challenge",
        "",
        "namespace Ampas.Refutations",
        "",
        f"/-- {claim}: {len(steps)} steps. -/",
        f"theorem {name} : ¬ ({target}) := fun h =>",
        f"  h.{conjunct} (",
    ]
    for n, s in enumerate(steps):
        rhs = (f".mp s{s.premises[0]} s{s.premises[1]}" if s.rule == "mp"
               else ".hyp rfl" if s.rule == "hyp" else f".{s.rule}")
        lines.append(f"    have s{n} : {derives} {theory} {fm_lean(s.formula)} := {rhs}")
    lines += [f"    s{len(steps) - 1})", "", "end Ampas.Refutations", ""]
    return "\n".join(lines)


