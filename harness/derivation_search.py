# --------------------------------------------------------------------------
# Driver: search, emit, and let the kernel decide
# --------------------------------------------------------------------------
import os
import subprocess

REFUT_DIR = ROOT / "build" / "refutations"


def _lean():
    from ampas_lean import _lean_root
    return _lean_root()


def _lean_env(extra_path: str = "") -> dict:
    env = dict(os.environ)
    root = _lean()
    env["PATH"] = f"{root / 'bin'}:{env.get('PATH', '')}"
    paths = [os.environ.get("AMPAS_TRUSTED_OLEAN",
                            str(ROOT / ".lake" / "build" / "lib" / "lean"))]
    if extra_path:
        paths.append(extra_path)
    env["LEAN_PATH"] = os.pathsep.join(paths)
    return env


def _run(cmd: list[str], env: dict, cwd: Path = ROOT, timeout: int = 900) -> tuple[int, str]:
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                           env=env, cwd=str(cwd), timeout=timeout)
    except subprocess.TimeoutExpired:
        return 124, f"timed out after {timeout}s"
    return r.returncode, ((r.stdout or "") + (r.stderr or "")).strip()


def check_witness(claim: str, cfg: dict, steps: list[Step], apply: str) -> dict:
    """Compile the witness, replay it through the kernel, and check that what
    it refutes is the frozen statement. The verdict is the kernel's."""
    REFUT_DIR.mkdir(parents=True, exist_ok=True)
    mod = claim.replace("-", "_") + "_refutation"
    decl = claim.lower().replace("-", "_") + "_refuted"
    target = (f"¬ ({cfg['statement']})" if cfg.get("statement_is_already_a_negation")
              else cfg["statement"])
    src = pl_witness_lean(decl, claim, steps, cfg["derives"], cfg["theory_lean"],
                          target, apply)
    path = REFUT_DIR / f"{mod}.lean"
    path.write_text(src, encoding="utf-8")

    env = _lean_env()
    out: dict = {"witness_file": str(path.relative_to(ROOT)), "steps": len(steps),
                 "refutation_decl": f"Ampas.Refutations.{decl}"}
    rc, msg = _run([str(_lean() / "bin" / "lean"), "-o", str(REFUT_DIR / f"{mod}.olean"),
                    str(path)], env)
    out["elaborates"] = rc == 0
    if rc != 0:
        out["error"] = msg[-900:]
        return out

    # kernel replay, in both modes, exactly as a submission gets
    env2 = _lean_env()
    env2["LEAN_PATH"] = env2["LEAN_PATH"] + os.pathsep + str(REFUT_DIR)
    for flag, key in ((None, "kernel_replay"), ("--fresh", "kernel_replay_fresh")):
        cmd = [str(_lean() / "bin" / "leanchecker")] + ([flag] if flag else []) + [mod]
        rc, msg = _run(cmd, env2)
        out[key] = rc == 0
        if rc != 0:
            out.setdefault("errors", []).append(f"{key}: {msg[-400:]}")

    # and the check that the refuted statement is the frozen one
    req = ROOT / ".refut_req.json"
    req.write_text(json.dumps({
        "reference_module": "AmpasRef.Challenge",
        "frozen_decl": cfg["frozen_decl"],
        "refutation_module": mod,
        "refutation_decl": f"Ampas.Refutations.{decl}"}), encoding="utf-8")
    try:
        rc, msg = _run([str(_lean() / "bin" / "lean"), "--run",
                        str(ROOT / "harness" / "CheckRefutation.lean"), str(req)], env2)
        if rc == 0 and msg:
            try:
                out["statement_check"] = json.loads(msg.strip().splitlines()[-1])
            except json.JSONDecodeError:
                out["statement_check_error"] = msg[-400:]
        else:
            out["statement_check_error"] = msg[-400:]
    finally:
        req.unlink(missing_ok=True)
    return out


def verdict(out: dict) -> str:
    """REFUTED only when every check the kernel does came back clean."""
    sc = out.get("statement_check") or {}
    ok = (out.get("elaborates") and out.get("kernel_replay")
          and out.get("kernel_replay_fresh") and sc.get("is_theorem")
          and sc.get("negates_frozen_statement_structurally")
          and not sc.get("uses_sorry")
          and not sc.get("foreign_statement_constants"))
    return "REFUTED" if ok else "REFUTATION_REJECTED"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "build" / "derivation_search.json"))
    ap.add_argument("--claim", action="append")
    ap.add_argument("--universe-size", type=int, default=48)
    ap.add_argument("--rounds", type=int, default=3)
    ap.add_argument("--term-depth", type=int, default=3)
    ap.add_argument("--subst-pool", type=int, default=20)
    args = ap.parse_args(argv)

    results = []
    for claim, cfg in CLAIMS.items():
        if args.claim and claim not in args.claim:
            continue
        t0 = time.monotonic()
        rec: dict = {"claim": claim, "frozen_decl": cfg["frozen_decl"],
                     "expected": cfg["expect"], "why": cfg["why"]}
        if cfg["kind"] == "pl":
            stats, steps = pl_search(
                cfg["theory"], [t for t, _ in cfg["targets"]],
                positive=cfg["positive"], universe_size=args.universe_size,
                rounds=args.rounds)
            rec["bound"] = {"formula_universe": stats["universe"],
                            "rounds": stats["rounds_run"],
                            "axiom_instances": stats["axiom_instances"],
                            "formulas_derived": stats["derived"],
                            "fragment": "A1,A2,MP" if cfg["positive"] else "A1,A2,A3,MP"}
            if steps is None:
                rec["outcome"] = "NO_DERIVATION"
            else:
                found = steps[-1].formula
                apply = next(a for t, a in cfg["targets"] if t == found)
                rec["derivation"] = [{"rule": s.rule, "formula": fm_lean(s.formula)}
                                     for s in steps]
                rec["kernel"] = check_witness(claim, cfg, steps, apply)
                rec["outcome"] = verdict(rec["kernel"])
        else:
            parts = []
            derived_any = False
            for part in cfg["parts"]:
                st, found = el_search(part["axioms"], part["goal"],
                                      term_depth=args.term_depth,
                                      subst_pool=args.subst_pool)
                parts.append({"part": part["name"], "derivable": found, "bound": st})
                derived_any |= found
            rec["bound"] = {"parts": parts, "method": "congruence closure"}
            # No proof-producing congruence closure here, so a hit could not be
            # handed to the kernel. Saying so beats recording a refutation
            # nothing checked.
            rec["outcome"] = ("DERIVATION_FOUND_BUT_UNVERIFIED" if derived_any
                              else "NO_DERIVATION")
        rec["seconds"] = round(time.monotonic() - t0, 1)
        rec["consistency"] = ("OK" if rec["outcome"] == cfg["expect"]
                              else f"EXPECTED_{cfg['expect']}_GOT_{rec['outcome']}")
        results.append(rec)
        extra = "" if rec["consistency"] == "OK" else f"  [{rec['consistency']}]"
        print(f"{claim:14s} {rec['outcome']:34s}{extra}", flush=True)

    out = {"searched_on": time.strftime("%Y-%m-%d"), "searches": results}
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n",
                              encoding="utf-8")
    print(f"\n-> {args.out}")
    return 1 if any(r["consistency"] != "OK" for r in results) else 0


if __name__ == "__main__":
    import sys
    sys.path.insert(0, str(ROOT / "harness"))
    raise SystemExit(main(sys.argv[1:]))
